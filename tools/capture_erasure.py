"""Capture `docs/evidence/erasure.md`, the transcript platform#18 quotes.

The Art. 17 post shows two things `qedro erasure` does, and this runs both against
inputs a reader can open:

1. **The evidenced run**, against `demo/lineage-declared`, where the demo's
   `acme.crm/subject-erasure` job emits the standard `lifecycleStateChange`, so the
   erasure instant is evidence rather than a typed `--since`; and the weekly dunning
   job is the descendant the erasure has not reached.
2. **The routine-overwrite trap** (#29). Spark reports `OVERWRITE` on every
   overwriting write, so on a table rewritten nightly the latest overwrite is last
   night's run rather than the erasure. Run once without `--since`, where several
   overwrites and nothing to choose between them withhold the mark, and once with it,
   where the first overwrite after the request is taken.

The demo has no dataset overwritten nightly, so the second input is generated here,
deterministically, into `docs/evidence/erasure-overwrites/`. Its events have the shape
`openlineage-spark` 1.53.0 gives an overwriting write in `tests/fixtures/spark-4.2.0` —
the facet on START, RUNNING and COMPLETE alike — and are synthetic, which the
transcript says.

The point of a captured transcript is that it is what the command printed, so this
runs the installed CLI and writes its output unedited. It **refuses a dirty working
tree**, because the file names the commit that produced it.

    python tools/capture_erasure.py            # rewrite the input and the transcript
    python tools/capture_erasure.py --check    # fail if either is out of date

`tests/test_erasure.py` asserts the same facts — `TestTheDemoEstate` for the first run,
`TestChoosingTheErasureAmongSeveral` for the second — but not the wording, so a change
to how the output reads leaves this file describing the commit it names until it is
recaptured.
"""

from __future__ import annotations

import argparse
import difflib
import json
import subprocess
import sys
import uuid
from datetime import UTC, datetime, timedelta
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
TARGET = REPO / "docs" / "evidence" / "erasure.md"
OVERWRITES = REPO / "docs" / "evidence" / "erasure-overwrites" / "events.ndjson"

SPARK = "https://github.com/OpenLineage/OpenLineage/tree/1.53.0/integration/spark"
AIRFLOW = "https://github.com/OpenLineage/OpenLineage/tree/1.53.0/integration/airflow"
SPEC = "https://openlineage.io/spec/2-0-2/OpenLineage.json#/$defs/RunEvent"
LIFECYCLE_SCHEMA = (
    "https://openlineage.io/spec/facets/1-0-1/LifecycleStateChangeDatasetFacet.json"
    "#/$defs/LifecycleStateChangeDatasetFacet"
)
RUNS = uuid.uuid5(uuid.NAMESPACE_URL, "https://cordata.tech/qedro/evidence/erasure")

#: Five nights of the snapshot job, and the morning the erasure was requested — after
#: the third night's overwrite, so the first overwrite after it is the fourth.
NIGHTS = [datetime(2026, 7, 20, 2, 10, tzinfo=UTC) + timedelta(days=n) for n in range(5)]
REQUESTED = "2026-07-22T10:00:00Z"
DATASET = "crm_curated.contacts_snapshot"

PREAMBLE = """# Transcript: `qedro erasure`, evidenced, and across routine overwrites

Captured by script from qedro {version}, at commit `{commit}` with a clean working tree,
on Python {python}. The output below is what each command printed, unedited. Run the
same commands from the repository root to reproduce it.

Two inputs. `demo/lineage-declared` is the demo company's three weeks of lineage, in
which `acme.crm/subject-erasure` overwrites `crm_raw.contacts` once, on 22 July, and
emits the standard `lifecycleStateChange` facet as it does.
`docs/evidence/erasure-overwrites/` is **synthetic**, generated by the same script:
five nights of a Spark job overwriting `crm_curated.contacts_snapshot`, in the event
shape `openlineage-spark` 1.53.0 gives an overwriting write in
`tests/fixtures/spark-4.2.0`, and a daily job reading it. The erasure was requested on
{requested}, after the third night's overwrite.

**What the second input is for.** Spark reports `OVERWRITE` on every overwriting write,
so on a table rewritten nightly most of those events are routine, and the latest is
last night's run rather than the erasure (cordata-tech/qedro#29). Without `--since`
qedro takes the latest and withholds the mark, because nothing says which run carried
out the erasure; with it, the first completed overwrite after the request is taken.
"""


def _overwrites() -> str:
    """The synthetic second input, as newline-delimited JSON."""
    events: list[dict] = []

    def dataset(name: str, *, overwrite: bool = False) -> dict:
        out: dict = {"namespace": "warehouse", "name": name}
        if overwrite:
            out["facets"] = {
                "lifecycleStateChange": {
                    "_producer": SPARK,
                    "_schemaURL": LIFECYCLE_SCHEMA,
                    "lifecycleStateChange": "OVERWRITE",
                }
            }
        return out

    def event(kind, when, producer, job, run, inputs, outputs) -> dict:
        return {
            "eventType": kind,
            "eventTime": when.isoformat(),
            "producer": producer,
            "schemaURL": SPEC,
            "run": {"runId": str(uuid.uuid5(RUNS, run))},
            "job": {"namespace": "acme.crm", "name": job, "facets": {}},
            "inputs": inputs,
            "outputs": outputs,
        }

    for night in NIGHTS:
        run = f"snapshot/{night.date()}"
        # The facet on every event of the run, as openlineage-spark sends it.
        for kind, offset in (("START", 0), ("RUNNING", 40), ("COMPLETE", 190)):
            events.append(
                event(
                    kind,
                    night + timedelta(seconds=offset),
                    SPARK,
                    "contacts_snapshot.overwrite",
                    run,
                    [dataset("crm_raw.contacts")],
                    [dataset(DATASET, overwrite=True)],
                )
            )
        morning = night.replace(hour=5, minute=0)
        for kind, offset in (("START", 0), ("COMPLETE", 120)):
            events.append(
                event(
                    kind,
                    morning + timedelta(seconds=offset),
                    AIRFLOW,
                    "segments-daily",
                    f"segments/{night.date()}",
                    [dataset(DATASET)],
                    [dataset("crm_curated.segments")],
                )
            )

    return "".join(json.dumps(e, sort_keys=True) + "\n" for e in events)


def _run(argv: list[str]) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [sys.executable, "-P", "-m", "qedro", *argv],
        cwd=REPO,
        capture_output=True,
        text=True,
        check=False,  # a non-zero exit is reported by the caller, not raised
    )


RUNS_TO_CAPTURE = [
    (
        (
            "## 1. The evidenced run\n\n"
            "The instant comes from the `lifecycleStateChange` the erasure job emitted, so "
            "the record states it as evidence, and names the descendant the erasure has not "
            "reached: the weekly dunning job, which has not run since."
        ),
        ["erasure", "demo/lineage-declared", "--dataset", "crm_raw.contacts"],
    ),
    (
        (
            "## 2a. Five nightly overwrites, without `--since`\n\n"
            "Five completed runs overwrote the dataset and nothing says which was the "
            "erasure, so the latest is taken and the mark is withheld, with the reason "
            "naming what to pass."
        ),
        ["erasure", "docs/evidence/erasure-overwrites", "--dataset", DATASET],
    ),
    (
        (
            "## 2b. The same, with the date the erasure was requested\n\n"
            "The window starts at the request, so the overwrites before it are out of view, "
            "and the first completed overwrite after it is taken. The scope states how many "
            "candidates there were and how the one used was chosen."
        ),
        [
            "erasure",
            "docs/evidence/erasure-overwrites",
            "--dataset",
            DATASET,
            "--since",
            REQUESTED,
        ],
    ),
]


def capture() -> str | int:
    from qedro import __version__

    commit = subprocess.run(
        ["git", "-C", str(REPO), "rev-parse", "--short", "HEAD"],
        capture_output=True,
        text=True,
        check=True,
    ).stdout.strip()
    python = ".".join(str(n) for n in sys.version_info[:3])
    parts = [
        PREAMBLE.format(version=__version__, commit=commit, python=python, requested=REQUESTED)
    ]
    for heading, argv in RUNS_TO_CAPTURE:
        result = _run(argv)
        if result.returncode != 0:
            print(f"qedro {' '.join(argv)} exited {result.returncode}:\n{result.stderr}")
            return 1
        parts.append(
            f"{heading}\n\n```console\n$ qedro {' '.join(argv)}\n{result.stdout}```\n"
            f"\nExit status {result.returncode}.\n"
        )
    return "\n".join(parts)


def _dirty() -> str:
    """Uncommitted changes, ignoring the captured evidence itself."""
    status = subprocess.run(
        ["git", "-C", str(REPO), "status", "--porcelain"],
        capture_output=True,
        text=True,
        check=True,
    ).stdout.splitlines()
    return "\n".join(line for line in status if "docs/evidence/" not in line).strip()


def _body(text: str) -> str:
    """Everything from the first run onwards, which is the part the output decides."""
    marker = "## 1. "
    return text[text.index(marker) :] if marker in text else text


def _diff(name: str, committed: str, now: str) -> None:
    print(f"{name} is out of date", file=sys.stderr)
    for line in difflib.unified_diff(
        committed.splitlines(), now.splitlines(), "committed", "this run", lineterm=""
    ):
        print(line, file=sys.stderr)


def main() -> int:
    parser = argparse.ArgumentParser(description="Capture the erasure transcript.")
    parser.add_argument("--check", action="store_true", help="fail if either file is out of date")
    args = parser.parse_args()

    if _dirty() and not args.check:
        print(
            "working tree is dirty; commit first so the transcript can name the commit it came from",
            file=sys.stderr,
        )
        return 2

    generated = _overwrites()
    if args.check:
        committed = OVERWRITES.read_text() if OVERWRITES.exists() else ""
        if committed != generated:
            _diff(str(OVERWRITES.relative_to(REPO)), committed, generated)
            return 1
    else:
        OVERWRITES.parent.mkdir(parents=True, exist_ok=True)
        OVERWRITES.write_text(generated)

    captured = capture()
    if isinstance(captured, int):
        return captured

    if args.check:
        current = TARGET.read_text() if TARGET.exists() else ""
        # The header names a version, a commit and a Python build, all of which move
        # for reasons that are not a change in the output.
        if _body(current) != _body(captured):
            _diff(str(TARGET.relative_to(REPO)), _body(current), _body(captured))
            return 1
        print(f"{TARGET.relative_to(REPO)} and its input match what the commands print")
        return 0

    TARGET.write_text(captured)
    print(f"wrote {TARGET.relative_to(REPO)} and {OVERWRITES.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
